def build():
    cases = []
    keys = [4, 22, 39, 57]
    for index, (name, gold, events) in enumerate(SCENARIOS):
        rng = random.Random('mindtrace-v3:' + name)
        fillers = DISTRACTORS * 3
        rng.shuffle(fillers)
        for mode in ['long', 'cross']:
            turns = []
            for n in range(1, 61):
                session = (n - 1) // 30 + 1 if mode == 'cross' else 1
                local = (n - 1) % 30 + 1 if mode == 'cross' else n
                at = datetime(2026, 9, 1, 19, tzinfo=timezone(timedelta(hours=8))) + timedelta(
                    days=index * 2 + (session - 1) * 7, minutes=local * 2)
                turns.append({'session': session, 'turn': local, 'global_turn': n,
                              'sent_at': at.isoformat(),
                              'user': events[keys.index(n)] if n in keys else fillers[n - 1],
                              'assistant': REPLIES[(n + index) % len(REPLIES)]})
            cases.append({'id': name + '_' + mode, 'scenario_id': name, 'mode': mode,
                          'gold_category': gold, 'gold_has_intent': gold is not None,
                          'key_global_turns': keys, 'turns': turns})
    assert len(SCENARIOS) == 30 and len(cases) == 60
    assert len({x['scenario_id'] for x in cases}) == 30
    for case in cases:
        for session in {t['session'] for t in case['turns']}:
            assert sum(t['session'] == session for t in case['turns']) >= 30
    return {'version': 3, 'synthetic': True,
            'authorship': '30 authored diagnostic trajectories; no independent human/clinical review',
            'n_independent_scenarios': 30, 'n_paired_variants': 60,
            'category_definitions': DEFINITIONS,
            'round_definition': 'one user message and one scripted assistant response',
            'protocol': 'final checkpoint; full timestamped bilateral baseline; no gold in prediction inputs; paired modes not independent',
            'cases': cases}


